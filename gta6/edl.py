CL = {}
for line in open(__file__.replace('edl.py', 'clips_list.txt')):
    if line.startswith('#') or not line.strip(): continue
    p = line.split()
    CL[p[0]] = (p[1], float(p[2]), float(p[3]))

def shots():
    out = []
    for (t, name, off), (t2, _, _) in zip(EDL, EDL[1:]):
        src, st, dur = CL[name]
        d = round(t2 - t, 3)
        out.append(dict(t=t, dur=d, name=name, src=src, ss=round(st + off, 3), off=off, cdur=dur))
    return out

if __name__ == '__main__':
    S = shots(); bad = 0; used = {}
    for s in S:
        if s['off'] + s['dur'] > s['cdur'] + 0.01:
            print('ДЛИННЕЕ КЛИПА:', s); bad += 1
        used.setdefault(s['src'], []).append((s['ss'], s['ss'] + s['dur'], s['name'], s['t']))
    for src, L in used.items():
        L.sort()
        for a, b in zip(L, L[1:]):
            if b[0] < a[1] - 0.01: print('ПОВТОР:', src, a, b); bad += 1
    print(len(S), 'планов, средний', round(sum(s['dur'] for s in S) / len(S), 2), 'с; ошибок', bad)
    sys.exit(1 if bad else 0)
